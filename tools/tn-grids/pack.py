# -*- coding: utf-8 -*-
"""Pack the two bundled Tunisia grids into the files the site and the backend read.

    python3 tools/tn-grids/pack.py

Inputs (made by the browser scripts in tools/tn-grids/README.md):
  soil_grid_tn.bin  148 × 84 cells of 0.05° (≈ 5 km), lat 30.2–37.6 N, lon 7.5–11.7 E.
                    Three planes, south→north rows, west→east columns:
                    clay %, sand %, organic carbon in 0.2 g/kg; 255 = no data (sea).
                    Each cell is the mean of 4 × 4 SoilGrids 2.0 samples (≈ 1.25 km apart)
                    of the depth-weighted 0–30 cm mean (0–5, 5–15, 15–30 cm).
  climate_tn.bin    16 × 7 points of the NASA POWER climatology (2001–2025, MERRA-2
                    0.5° × 0.625°), lat 30–37.5 N, lon 7.5–11.25 E. Per point 48 bytes:
                    12 × rain mm, 12 × ET0 mm / 2, 12 × (Tmax + 20) × 4, 12 × (Tmin + 20) × 4.
                    ET0 = FAO-56 Penman–Monteith on the monthly means (js/climate-core.js).
Outputs: js/soil-grid-tn.js, js/climate-tn.js, backend/data/soil_grid_tn.json,
         backend/data/climate_tn.json
"""
import base64
import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

CLIMATE_ELEV = [268, 288, 316, 359, 403, 505, 587, 219, 243, 265, 306, 364, 489, 580, 184, 198, 231, 285, 361, 482, 567,
                160, 178, 212, 267, 356, 479, 549, 141, 158, 197, 262, 355, 403, 358, 117, 133, 172, 246, 342, 235, 109,
                90, 87, 107, 185, 308, 198, 39, 49, 36, 41, 149, 225, 70, 5, 47, 88, 138, 109, 55, 5, 0, 343, 483, 417,
                335, 102, 35, 2, 920, 965, 761, 408, 186, 72, 12, 1007, 945, 858, 530, 187, 50, 8, 862, 659, 624, 571,
                230, 36, 1, 427, 486, 352, 337, 163, 69, 8, 48, 52, 157, 163, 54, 23, 6, 0, 0, 3, 22, 3, 0, 0]

SOIL = {
    "source": "SoilGrids 2.0 (ISRIC), grille GAIA 5 km pré-calculée",
    "url": "https://www.isric.org/explore/soilgrids",
    "service": "https://maps.isric.org (WCS, couches clay / sand / soc, moyenne, 0–5, 5–15, 15–30 cm)",
    "lat0": 30.2, "lon0": 7.5, "step": 0.05, "nLat": 148, "nLon": 84,
    "layout": "3 planes (clay %, sand %, SOC × 5 g/kg), rows south→north, cols west→east, 255 = no data",
    "sampled": "2026-11-21",
}
CLIMATE = {
    "source": "Table GAIA intégrée : normales NASA POWER 2001–2025 (MERRA-2)",
    "url": "https://power.larc.nasa.gov/",
    "lats": [30 + 0.5 * i for i in range(16)],
    "lons": [7.5 + 0.625 * i for i in range(7)],
    "elev": CLIMATE_ELEV,
    "period": "2001–2025",
    "layout": "per point 48 bytes: rain mm ×12, ET0 mm/2 ×12, (Tmax+20)×4 ×12, (Tmin+20)×4 ×12",
    "sampled": "2026-11-21",
}


def b64(path):
    return base64.b64encode(open(os.path.join(HERE, path), 'rb').read()).decode('ascii')


def js_file(name, var, meta, data, body):
    head = json.dumps(meta, ensure_ascii=False, indent=2)
    return (u"/* Generated by tools/tn-grids/pack.py — do not edit by hand. See tools/tn-grids/README.md. */\n"
            u"(function (global) {\n  'use strict';\n  var META = " + head.replace('\n', '\n  ') + u";\n"
            u"  var DATA = '" + data + u"';\n" + body +
            u"  global." + var + u" = Object.assign({ lookup: lookup }, META);\n"
            u"}(typeof window !== 'undefined' ? window : this));\n")


DECODE = u"""  function bytes(s) {
    if (typeof atob === 'function') { var b = atob(s), u = new Uint8Array(b.length); for (var i = 0; i < b.length; i++) u[i] = b.charCodeAt(i); return u; }
    return new Uint8Array(Buffer.from(s, 'base64'));
  }
  function km(aLat, aLon, bLat, bLon) {
    var r = Math.PI / 180, dLat = (bLat - aLat) * r, dLon = (bLon - aLon) * r;
    var h = Math.sin(dLat / 2) * Math.sin(dLat / 2) + Math.cos(aLat * r) * Math.cos(bLat * r) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
    return 12742 * Math.asin(Math.sqrt(h));
  }
  var U = null;
"""

SOIL_BODY = DECODE + u"""  // value of the 5 km cell holding (lat, lon); on the coast, the nearest cell with data within 2 cells
  function lookup(lat, lon) {
    if (!U) U = bytes(DATA);
    var n = META.nLat * META.nLon;
    var r0 = Math.floor((lat - META.lat0) / META.step), c0 = Math.floor((lon - META.lon0) / META.step);
    if (r0 < -2 || c0 < -2 || r0 > META.nLat + 1 || c0 > META.nLon + 1) return null;
    var best = null;
    for (var dr = -2; dr <= 2; dr++) for (var dc = -2; dc <= 2; dc++) {
      var r = r0 + dr, c = c0 + dc;
      if (r < 0 || c < 0 || r >= META.nLat || c >= META.nLon) continue;
      var k = r * META.nLon + c;
      if (U[k] === 255) continue;
      var cLat = META.lat0 + (r + 0.5) * META.step, cLon = META.lon0 + (c + 0.5) * META.step;
      var d = (dr === 0 && dc === 0) ? 0 : km(lat, lon, cLat, cLon);
      if (!best || d < best.km) best = { clay_pct: U[k], sand_pct: U[n + k], soc: Math.round(U[2 * n + k] * 2) / 10, km: d, cell: [cLat, cLon] };
    }
    if (best) best.km = Math.round(best.km);
    return best;
  }
"""

CLIMATE_BODY = DECODE + u"""  function point(i) {
    var o = i * 48, m, p = { rain: [], et0: [], tmax: [], tmin: [] };
    for (m = 0; m < 12; m++) {
      p.rain.push(U[o + m]); p.et0.push(U[o + 12 + m] * 2);
      p.tmax.push(U[o + 24 + m] / 4 - 20); p.tmin.push(U[o + 36 + m] / 4 - 20);
    }
    return p;
  }
  // bilinear interpolation between the 4 surrounding grid points; null outside the grid
  function lookup(lat, lon) {
    if (!U) U = bytes(DATA);
    var la = META.lats, lo = META.lons, nLo = lo.length;
    var fy = (lat - la[0]) / (la[1] - la[0]), fx = (lon - lo[0]) / (lo[1] - lo[0]);
    if (fy < -0.5 || fx < -0.5 || fy > la.length - 0.5 || fx > nLo - 0.5) return null;
    fy = Math.max(0, Math.min(la.length - 1.0001, fy)); fx = Math.max(0, Math.min(nLo - 1.0001, fx));
    var y = Math.floor(fy), x = Math.floor(fx), ty = fy - y, tx = fx - x;
    var w = [[y, x, (1 - ty) * (1 - tx)], [y, x + 1, (1 - ty) * tx], [y + 1, x, ty * (1 - tx)], [y + 1, x + 1, ty * tx]];
    var out = { rain: [], et0: [], tmax: [], tmin: [] }, near = Infinity;
    w.forEach(function (q) { near = Math.min(near, km(lat, lon, la[q[0]], lo[q[1]])); });
    ['rain', 'et0', 'tmax', 'tmin'].forEach(function (key) {
      for (var m = 0; m < 12; m++) {
        var s = 0;
        w.forEach(function (q) { s += point(q[0] * nLo + q[1])[key][m] * q[2]; });
        out[key].push(s);
      }
    });
    var sum = function (a) { return a.reduce(function (s, v) { return s + v; }, 0); };
    return {
      rain_mm: sum(out.rain), et0_mm: sum(out.et0),
      tmax_hot: Math.max.apply(null, out.tmax), tmin_cold: Math.min.apply(null, out.tmin),
      monthly: out, km: Math.round(near)
    };
  }
"""


def main():
    soil, clim = b64('soil_grid_tn.bin'), b64('climate_tn.bin')
    w = lambda p, s: io.open(os.path.join(ROOT, p), 'w', encoding='utf-8', newline='\n').write(s)
    w('js/soil-grid-tn.js', js_file('soil', 'GAIA_SOIL_GRID', SOIL, soil, SOIL_BODY))
    w('js/climate-tn.js', js_file('climate', 'GAIA_CLIMATE_TN', CLIMATE, clim, CLIMATE_BODY))
    w('backend/data/soil_grid_tn.json', json.dumps(dict(SOIL, data=soil), ensure_ascii=False))
    w('backend/data/climate_tn.json', json.dumps(dict(CLIMATE, data=clim), ensure_ascii=False))
    print('packed soil', len(soil), 'climate', len(clim))


if __name__ == '__main__':
    main()
